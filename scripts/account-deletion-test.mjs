import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const read = async (path) => readFile(new URL("../" + path, import.meta.url), "utf8");
const route = await read("src/app/api/account/delete/route.js");
const start = await read("src/app/api/auth/google/start/route.js");
const callback = await read("src/app/api/auth/google/callback/route.js");
const ui = await read("src/components/client/ui.jsx");
const session = await read("src/lib/auth/session.js");
for (const marker of ["getSessionUser", "verifyPassword", "DELETE MY ACCOUNT", "request.nextUrl.origin", "prisma.user.delete", "clearSession"]) assert.ok(route.includes(marker), marker);
assert.ok(route.includes("GOOGLE_REAUTH_REQUIRED"));
assert.ok(start.includes('intent === "delete-account"'));
assert.ok(start.includes("IDENTITY_SCOPES"));
assert.ok(callback.includes('intent === "delete-account"'));
assert.ok(callback.includes("email !== user.email.toLowerCase()"));
assert.ok(callback.includes("prisma.user.delete"));
assert.ok(callback.includes("clearSession"));
assert.ok(session.includes("hasPassword: Boolean(passwordHash)"));
assert.ok(ui.includes("Delete account"));
assert.ok(ui.includes("intent=delete-account"));
console.log("PASS account deletion requires password or verified Google identity and clears the session");
